// Package portscan проверяет доступность TCP-портов на одном или нескольких
// хостах методом TCP Connect (полное установление соединения через
// стандартный сетевой стек Go).
//
// Базовый сценарий:
//
//	scanner, err := portscan.New(
//		portscan.WithConcurrency(100),
//		portscan.WithConnectTimeout(500*time.Millisecond),
//	)
//	if err != nil {
//		return err
//	}
//	results, err := scanner.Scan(ctx,
//		[]string{"192.168.1.10", "example.com"},
//		portscan.Union(portscan.Range(1, 1024), portscan.List(8080, 8443)),
//	)
//	if err != nil {
//		return err // некорректные цели или порты
//	}
//	for r := range results {
//		fmt.Println(r.Host, r.IP, r.Port, r.State)
//	}
//
// Scan проверяет входные данные синхронно и возвращает итератор
// [iter.Seq]. Сканирование начинается при первом проходе по итератору,
// результаты отдаются по мере готовности (порядок не гарантируется).
// Выход из цикла (break) или отмена контекста останавливают выдачу
// новых проверок; к моменту выхода из цикла все запущенные проверки
// завершены, а все внутренние горутины остановлены.
//
// Пакет не использует глобального изменяемого состояния; один [Scanner]
// безопасно использовать из нескольких горутин и для нескольких
// одновременных сканирований.
